// Generates the content/ tree and every _meta.ts from data/roadmap.mjs, so the
// sidebar order always matches the roadmap rather than being maintained by hand.
//
// Topic with subtopics -> folder with index.mdx + one file per subtopic.
// Topic without subtopics -> a single .mdx file.
//
// Existing .mdx files are never overwritten: re-running this adds whatever is
// missing and rewrites only the _meta.ts files. Pass --list to print a report of
// which pages are still placeholders.
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { sections } from '../data/roadmap.mjs'

const ROOT = 'content'
const listOnly = process.argv.includes('--list')

const PLACEHOLDER = '{/* placeholder */}'

const metaFile = (entries) =>
  `import type { MetaRecord } from 'nextra'\n\n` +
  `// Generated by scripts/scaffold.mjs - edit data/roadmap.mjs instead.\n` +
  `const meta: MetaRecord = {\n${entries.map((e) => `  ${e}`).join('\n')}\n}\n\nexport default meta\n`

const key = (k) => (/^[a-z][a-z0-9]*$/i.test(k) ? k : `'${k}'`)

const frontmatter = (title, description) =>
  `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n`

const sourceTag = (node) => {
  const parts = []
  if (node.docs?.length) parts.push(`docs={${JSON.stringify(node.docs)}}`)
  if (node.api?.length) parts.push(`api={${JSON.stringify(node.api)}}`)
  if (node.external) parts.push(`external=${JSON.stringify(node.external)}`)
  return `<DocSource ${parts.join(' ')} />`
}

const stub = (node, title) =>
  `${frontmatter(title, `${title} in Kotlin.`)}\n# ${title}\n\n${sourceTag(node)}\n\n${PLACEHOLDER}\n`

let created = 0
const placeholders = []

async function ensure(path, contents) {
  if (existsSync(path)) {
    const current = await readFile(path, 'utf8')
    if (current.includes(PLACEHOLDER)) placeholders.push(path)
    return
  }
  placeholders.push(path)
  if (listOnly) return
  await writeFile(path, contents)
  created++
}

await mkdir(ROOT, { recursive: true })

for (const section of sections) {
  const dir = `${ROOT}/${section.slug}`
  if (!listOnly) await mkdir(dir, { recursive: true })

  const entries = ['index: { title: \'Overview\' },']
  for (const topic of section.topics) {
    entries.push(`${key(topic.slug)}: ${JSON.stringify({ title: topic.title })},`)
  }
  if (!listOnly) await writeFile(`${dir}/_meta.ts`, metaFile(entries))

  await ensure(
    `${dir}/index.mdx`,
    `${frontmatter(section.title, `${section.title} - overview of every concept in this part of the Kotlin roadmap.`)}\n# ${section.title}\n\n${PLACEHOLDER}\n`
  )

  for (const topic of section.topics) {
    if (topic.subs?.length) {
      const tdir = `${dir}/${topic.slug}`
      if (!listOnly) await mkdir(tdir, { recursive: true })

      const subEntries = ['index: { title: \'Overview\' },']
      for (const sub of topic.subs) {
        subEntries.push(`${key(sub.slug)}: ${JSON.stringify({ title: sub.title })},`)
      }
      if (!listOnly) await writeFile(`${tdir}/_meta.ts`, metaFile(subEntries))

      await ensure(`${tdir}/index.mdx`, stub(topic, topic.title))
      for (const sub of topic.subs) {
        await ensure(`${tdir}/${sub.slug}.mdx`, stub(sub, sub.title))
      }
    } else {
      await ensure(`${dir}/${topic.slug}.mdx`, stub(topic, topic.title))
    }
  }
}

// Top level
const topEntries = [
  "index: { title: 'Kotlin Learn', theme: { breadcrumb: false } },",
  ...sections.map((s) => `${key(s.slug)}: ${JSON.stringify({ title: s.title })},`),
  // Hand-written pages that are not roadmap nodes. Listed here so this
  // generator does not drop them from content/_meta.ts.
  "playground: { title: 'Playground', theme: { layout: 'full', toc: false } },",
  "attribution: { title: 'Attribution' },"
]
if (!listOnly) await writeFile(`${ROOT}/_meta.ts`, metaFile(topEntries))

if (listOnly) {
  console.log(`placeholders / missing (${placeholders.length}):`)
  for (const p of placeholders) console.log(`  ${p}`)
} else {
  console.log(`created ${created} new page(s)`)
  console.log(`still placeholders: ${placeholders.length}`)
}
